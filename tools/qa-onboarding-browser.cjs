'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {chromium}=require('playwright');
const url=process.env.HIGH_NOTES_QA_URL||'http://127.0.0.1:4173/';
const out=process.env.HIGH_NOTES_QA_OUT||path.join(os.tmpdir(),'high-notes-onboarding');
const executablePath=[process.env.HIGH_NOTES_BROWSER,'C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p=>p&&fs.existsSync(p));
fs.mkdirSync(out,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath});
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.setDefaultTimeout(15000);
  const shot=name=>page.screenshot({path:path.join(out,name+'.png')});
  const state=()=>page.evaluate(()=>window.__HIGH_NOTES__.snapshot().state);
  const step=n=>page.waitForFunction(n=>window.__HIGH_NOTES__.snapshot().state.tutorial.step===n,n);
  const done=()=>page.locator('#tutorialPanel.lesson-complete').waitFor();
  const next=async n=>{await done();await page.locator('#tutorialDoButton').click();await step(n);};
  const hold=async(key,ms)=>{await page.keyboard.down(key);await page.waitForTimeout(ms);await page.keyboard.up(key);};
  try{
    await page.goto(url,{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>document.getElementById('gameCanvas')?.dataset.runtimeReady==='true');
    await page.locator('#startButton').click();
    await page.locator('#characterName').fill('First Verse');
    await page.locator('#confirmCharacter').click();
    await page.locator('#interfaceSetupCard:not([hidden])').waitFor();
    assert.equal(await page.locator('#tutorialPanel').getAttribute('hidden'),'');
    await page.locator('#onboardingInterfaceSize').fill('125');
    assert.equal(await page.locator('#onboardingInterfaceSizeValue').textContent(),'125%');
    assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).fontSize),'20px');
    await shot('01-size-desktop-125');
    for(const viewport of [{width:390,height:844},{width:844,height:390}]){
      await page.setViewportSize(viewport);
      await page.locator('#interfaceSetupBegin').scrollIntoViewIfNeeded();
      const r=await page.locator('#interfaceSetupBegin').boundingBox();
      assert.ok(r.x>=0&&r.y>=0&&r.x+r.width<=viewport.width+1&&r.y+r.height<=viewport.height+1,'begin button reachable at maximum size');
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal overflow');
      await shot('02-size-'+viewport.width+'-125');
    }
    await page.setViewportSize({width:1440,height:900});
    await page.locator('#onboardingInterfaceSize').fill('85');
    assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).fontSize),'13.6px');
    await page.locator('#onboardingInterfaceSize').fill('100');
    await page.locator('#interfaceSetupBack').click();
    assert.equal(await page.locator('#characterName').inputValue(),'First Verse','back preserves character choices');
    await page.locator('#confirmCharacter').click();
    await page.locator('#interfaceSetupBegin').click();
    await step(0);
    await page.keyboard.press('Space'); // Early actions must not bank later lessons.
    await page.keyboard.down('d');await done();await page.keyboard.up('d');
    assert.equal((await state()).tutorial.step,0,'completion waits for acknowledgement');
    await shot('03-movement-complete');
    await page.keyboard.press('e');await step(1);
    await page.evaluate(()=>window.__HIGH_NOTES__.debug.teleport(445,520));
    await page.keyboard.press('e');await next(2);
    assert.equal(await page.locator('#tutorialPanel').evaluate(el=>el.classList.contains('lesson-complete')),false,'early attack did not skip its lesson');
    await page.keyboard.press('Space');await next(3);
    await page.keyboard.down('Space');await done();await page.keyboard.up('Space');await next(4);
    await page.keyboard.press('Shift');await next(5);
    await hold('f',250);await next(6);
    await page.keyboard.press('q');await next(7);
    await page.keyboard.press('c');await next(8);
    await page.keyboard.press('e');await next(9);
    await page.locator('#tutorialDoButton').click();
    assert.equal(await page.locator('#inventoryActionButton').textContent(),'Use Field Tonic');
    await page.locator('#inventoryActionButton').click();
    await page.locator('#closeInventoryButton').click();await next(10);
    await page.locator('#tutorialDoButton').click();
    await page.locator('#inventoryActionButton').click();
    await page.locator('#closeInventoryButton').click();await next(11);
    await shot('04-ready-for-mossvale');
    await page.locator('#tutorialDoButton').click();
    assert.equal((await state()).tutorial.status,'completed');
    assert.equal((await state()).inventory.equipped.armour,'grooveguard-vest');
    await page.keyboard.press('Escape');
    await page.locator('#pauseSettingsButton').click();
    await page.getByRole('tab',{name:'Display',exact:true}).click();
    await page.locator('#interfaceSize').fill('115');
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>document.getElementById('gameCanvas')?.dataset.runtimeReady==='true');
    assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).fontSize),'18.4px','size persists on reload');
    await page.locator('#continueButton').click();
    assert.equal((await state()).tutorial.status,'completed','tutorial completion survives reload');
    await shot('05-campaign-after-reload');
    const padContext=await browser.newContext({viewport:{width:1280,height:720}});
    await padContext.addInitScript(()=>{
      const buttons=Array.from({length:20},()=>({pressed:false,touched:false,value:0}));
      const pad={id:'Onboarding QA',index:0,connected:true,mapping:'standard',timestamp:1,buttons,axes:[0,0,0,0]};
      Object.defineProperty(navigator,'getGamepads',{configurable:true,value:()=>[pad]});
      window.qaPad=(index,down)=>{buttons[index].pressed=down;buttons[index].value=down?1:0;pad.timestamp++;};
      window.qaMove=amount=>{pad.axes[0]=amount;pad.timestamp++;};
    });
    const padPage=await padContext.newPage();padPage.on('pageerror',e=>errors.push(e.message));
    await padPage.goto(url,{waitUntil:'domcontentloaded'});
    await padPage.waitForFunction(()=>document.getElementById('gameCanvas')?.dataset.runtimeReady==='true');
    await padPage.locator('#startButton').click();await padPage.locator('#confirmCharacter').click();
    await padPage.waitForFunction(()=>document.activeElement.id==='onboardingInterfaceSize');
    async function pressPad(index){await padPage.evaluate(i=>window.qaPad(i,true),index);await padPage.waitForTimeout(140);await padPage.evaluate(i=>window.qaPad(i,false),index);await padPage.waitForTimeout(140);}
    await pressPad(15);
    assert.equal(await padPage.locator('#onboardingInterfaceSize').inputValue(),'105','D-pad adjusts size');
    await padPage.locator('#interfaceSetupBegin').focus();await pressPad(0);
    await padPage.locator('#tutorialPanel:not([hidden])').waitFor();
    await padPage.evaluate(()=>window.qaMove(1));
    await padPage.locator('#tutorialPanel.lesson-complete').waitFor();
    await padPage.evaluate(()=>window.qaMove(0));await pressPad(3);
    await padPage.waitForFunction(()=>window.__HIGH_NOTES__.snapshot().state.tutorial.step===1);
    assert.match(await padPage.locator('#tutorialControl').textContent(),/Y/);
    await padContext.close();
    const touchContext=await browser.newContext({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
    const touchPage=await touchContext.newPage();touchPage.on('pageerror',e=>errors.push(e.message));
    await touchPage.goto(url,{waitUntil:'domcontentloaded'});
    await touchPage.waitForFunction(()=>document.getElementById('gameCanvas')?.dataset.runtimeReady==='true');
    await touchPage.locator('#startButton').tap();await touchPage.locator('#confirmCharacter').tap();
    await touchPage.locator('#onboardingInterfaceSize').scrollIntoViewIfNeeded();
    const slider=await touchPage.locator('#onboardingInterfaceSize').boundingBox();
    await touchPage.touchscreen.tap(slider.x+slider.width*.8,slider.y+slider.height/2);
    assert.ok(Number(await touchPage.locator('#onboardingInterfaceSize').inputValue())>100,'touch adjusts size');
    await touchPage.locator('#interfaceSetupBegin').tap();
    await touchPage.locator('#tutorialPanel:not([hidden])').waitFor();
    await touchPage.waitForFunction(()=>document.getElementById('tutorialControl').textContent.includes('Drag'));
    await touchPage.screenshot({path:path.join(out,'06-touch-tutorial.png')});
    await touchContext.close();
    assert.deepEqual(errors,[]);
    console.log('Onboarding browser QA passed: size preview 85–125%, mobile layouts, keyboard/gamepad/touch, back navigation, all 12 lessons, no banked actions, equipment, settings and save/reload. Screenshots: '+out);
  }catch(error){await shot('FAILURE');throw error;}
  finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
